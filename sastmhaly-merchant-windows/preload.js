const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktopAPI', {
  getStatus: () => ipcRenderer.invoke('api:status'),
  setupStore: (data) => ipcRenderer.invoke('api:setup', data),
  getSettings: () => ipcRenderer.invoke('api:get-settings'),
  saveSettings: (data) => ipcRenderer.invoke('api:save-settings', data),
  getDashboard: () => ipcRenderer.invoke('api:dashboard'),
  getProducts: (search, category_id) => ipcRenderer.invoke('api:products', { search, category_id }),
  saveProduct: (data) => ipcRenderer.invoke('api:save-product', data),
  deleteProduct: (id) => ipcRenderer.invoke('api:delete-product', id),
  getCategories: () => ipcRenderer.invoke('api:categories'),
  getUnits: () => ipcRenderer.invoke('api:units'),
  getInventory: () => ipcRenderer.invoke('api:inventory'),
  adjustInventory: (data) => ipcRenderer.invoke('api:adjust-inventory', data),
  getSales: () => ipcRenderer.invoke('api:sales'),
  getSale: (id) => ipcRenderer.invoke('api:sale', id),
  commitSale: (data) => ipcRenderer.invoke('api:commit-sale', data),
  getCustomers: (search) => ipcRenderer.invoke('api:customers', search),
  saveCustomer: (data) => ipcRenderer.invoke('api:save-customer', data),
  recordCustomerPayment: (data) => ipcRenderer.invoke('api:customer-payment', data),
  getSuppliers: () => ipcRenderer.invoke('api:suppliers'),
  saveSupplier: (data) => ipcRenderer.invoke('api:save-supplier', data),
  getPurchases: () => ipcRenderer.invoke('api:purchases'),
  savePurchase: (data) => ipcRenderer.invoke('api:save-purchase', data),
  getCurrentShift: () => ipcRenderer.invoke('api:shifts-current'),
  openShift: (data) => ipcRenderer.invoke('api:open-shift', data),
  closeShift: (data) => ipcRenderer.invoke('api:close-shift', data),
  addCashMovement: (data) => ipcRenderer.invoke('api:cash-movement', data),
  getShiftsHistory: () => ipcRenderer.invoke('api:shifts-history'),
  getExpenses: () => ipcRenderer.invoke('api:expenses'),
  saveExpense: (data) => ipcRenderer.invoke('api:save-expense', data),
  getEmployees: () => ipcRenderer.invoke('api:employees'),
  saveEmployee: (data) => ipcRenderer.invoke('api:save-employee', data),
  recordAdjustment: (data) => ipcRenderer.invoke('api:adjustment', data),
  getPayroll: (month, year) => ipcRenderer.invoke('api:payroll', { month, year }),
  calculatePayroll: (data) => ipcRenderer.invoke('api:calculate-payroll', data),
  paySalary: (id) => ipcRenderer.invoke('api:pay-salary', id),
  getReports: (type) => ipcRenderer.invoke('api:reports', type),
  backup: () => ipcRenderer.invoke('api:backup')
});

